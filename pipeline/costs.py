"""Write COSTS.md from runs.jsonl: measured latency and spend per stage and per model, and
what the finished film itself cost.

Run: uv run python -m pipeline.costs   (or: make costs)
"""

import json
import statistics
from collections import defaultdict

from pipeline import keyframes, music, narration, shots
from pipeline import storyboard as sb
from pipeline.common.workspace import runs_file

COSTS_FILE = sb.ROOT / "COSTS.md"
HOSTED_GPU_STAGES = {"shots", "music"}


def load_runs():
    return [json.loads(line) for line in runs_file().read_text(encoding="utf-8").splitlines() if line.strip()]


def money(value):
    return f"${value:.4f}" if value else "$0"


def summarize(records):
    ok = [r for r in records if r["status"] == "ok"]
    latencies = [r["latency_s"] for r in ok]
    return {
        "calls": len(records),
        "ok": len(ok),
        "failed": len(records) - len(ok),
        "median_s": statistics.median(latencies) if latencies else 0,
        "total_min": sum(r["latency_s"] for r in records) / 60,
        "billed": sum(r.get("billed_usd") or 0 for r in records),
        "list": sum(r.get("list_price_usd") or 0 for r in ok),
    }


def table(groups, label):
    rows = [f"| {label} | Calls | OK | Failed | Median latency | Total time | Billed | List-price equivalent |", "|---|---|---|---|---|---|---|---|"]
    for name, records in sorted(groups.items()):
        s = summarize(records)
        rows.append(
            f"| {name} | {s['calls']} | {s['ok']} | {s['failed']} | {s['median_s']:.1f} s | {s['total_min']:.1f} min | {money(s['billed'])} | {money(s['list'])} |"
        )
    return "\n".join(rows)


def film_files(storyboard):
    used_characters = {c for shot in storyboard["shots"] for c in shot.get("characters", [])}
    files = [narration.line_audio_path(storyboard, s, i) for s in storyboard["shots"] for i, _ in enumerate(s["lines"])]
    files += [keyframes.reference_path(storyboard, c) for c in used_characters]
    files += [keyframes.keyframe_path(storyboard, s) for s in storyboard["shots"]]
    files += [shots.best_clip(storyboard, s) for s in storyboard["shots"]]
    files += [music.chosen_track(storyboard)]
    return {p.name for p in files if p}


def write(path=sb.DEFAULT_PATH):
    runs = load_runs()
    storyboard = sb.load(path)
    by_stage, by_model = defaultdict(list), defaultdict(list)
    for r in runs:
        by_stage[r["stage"]].append(r)
        by_model[f"`{r['model']}`"].append(r)

    names = film_files(storyboard)
    in_film = [r for r in runs if r["status"] == "ok" and isinstance(r.get("output"), str) and r["output"].rsplit("/", 1)[-1] in names]
    film = summarize(in_film)
    everything = summarize(runs)
    gpu_minutes = sum(r["latency_s"] for r in runs if r["stage"] in HOSTED_GPU_STAGES and r["status"] == "ok") / 60

    COSTS_FILE.write_text(
        f"""# Costs

Generated by `make costs` from `runs.jsonl` ({len(runs)} logged model calls). Do not edit by hand; edit `pipeline/costs.py`.

## Summary

| | Calls | Billed | List-price equivalent |
|---|---|---|---|
| **Everything we ran** (smoke tests, experiments, retries, failures) | {everything['calls']} | {money(everything['billed'])} | {money(everything['list'])} |
| **Only the calls whose output is in the finished film** | {film['calls']} | {money(film['billed'])} | {money(film['list'])} |

- **Billed** is money actually spent. Grok on OpenRouter reports its real cost (`usage.cost`). WaveSpeed's cost is our estimate from its price page, and it came out of the $1 sign-up credit. Gemini and Cloudflare calls were on free tiers, so they billed $0.
- **List-price equivalent** is what the same calls would cost at published prices without free tiers. Gemini text and TTS prices come from token counts. Cloudflare's comes from 512×512 output tiles.
- **Addis AI** bills in ETB per token and returns token counts, not a price. We log the tokens (in `usage`), not a dollar figure. The full-script translation used 2,269 input and 477 output tokens, about 1.06 ETB.

## GPU time

Nothing ran on our own GPU. Video and music ran on hosted GPUs, where the provider's queue and compute time is what we measure as latency. Successful calls in the `shots` and `music` stages add up to **{gpu_minutes:.1f} minutes** of wall-clock time. That is an upper bound on GPU minutes, because it includes upload, queue and download time.

## By stage

{table(by_stage, "Stage")}

## By model

{table(by_model, "Model")}

## Notes

- **Open vs frontier, same shot (EXPERIMENTS.md E6).** Wan 2.2 at 480p cost about $0.08 for an 8 s clip in ~70 s. Grok Imagine Video 1.5 Lite at 720p cost $0.25 in 47 s. The film uses Grok, at $0.03 per second of 720p plus $0.01 per input image.
- **Free tiers used:** Gemini API (text, TTS), Cloudflare Workers AI (about 10,000 neurons a day, roughly 75 FLUX.2 klein images), and the WaveSpeed $1 sign-up credit.
- **Rate limits met** (FAILURES.md): Gemini 3.8 Flash 503 "high demand", Gemini 3.8 Flash TTS 429, and WaveSpeed 429 "Concurrency" at 4 parallel jobs.
- Prices were checked on 2026-11-25 and 2026-11-26. See `docs/research/external-services.md` for sources.
""",
        encoding="utf-8",
    )
    print(f"COSTS.md: {len(runs)} calls; film {money(film['billed'])} billed, {money(film['list'])} list; everything {money(everything['billed'])} billed")


if __name__ == "__main__":
    write()
